//! Runner-owned SSH credentials and strict structured-connection arguments.
//! Secret bytes never become argv, environment values, debug output, registry
//! metadata, or model-visible responses. Only the native askpass subprocess may
//! release one bounded credential to the already pinned OpenSSH connection.


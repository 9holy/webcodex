const ASKPASS_REQUEST_ENV: &str = "WEBCODEX_SSH_ASKPASS_REQUEST";
const ASKPASS_NONCE_ENV: &str = "WEBCODEX_SSH_ASKPASS_NONCE";
const KNOWN_HOSTS_PATH_ENV: &str = "WEBCODEX_SSH_KNOWN_HOSTS_FILE";
const IDENTITY_PATH_ENV: &str = "WEBCODEX_SSH_IDENTITY_FILE";
const LITERAL_DOLLAR_ENV: &str = "WEBCODEX_SSH_LITERAL_DOLLAR";
const WINDOWS_PATH_OPTION_MAX_BYTES: usize = 16 * 1024;
#[cfg(any(windows, test))]
const WINDOWS_COMMAND_LINE_MAX_UNITS: usize = 32 * 1024 - 1;
const SECRET_MAX_BYTES: usize = 4096;
const SECRET_FILE_MAX_BYTES: usize = 32 * 1024;
const ASKPASS_LIFETIME_SECS: u64 = 30;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum StoredAuthentication {
    ExistingEnvironment,
    Password,
    IdentityFile,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct HostKey {
    pub(crate) algorithm: String,
    pub(crate) public_key: String,
    pub(crate) fingerprint: String,
}

impl HostKey {
    pub(crate) fn parse(algorithm: &str, public_key: &str) -> Result<Self, &'static str> {
        if !matches!(
            algorithm,
            "ssh-ed25519"
                | "ecdsa-sha2-nistp256"
                | "ecdsa-sha2-nistp384"
                | "ecdsa-sha2-nistp521"
                | "ssh-rsa"
        ) || public_key.len() > 12 * 1024
        {
            return Err("ssh_host_key_invalid");
        }
        let bytes = general_purpose::STANDARD
            .decode(public_key)
            .map_err(|_| "ssh_host_key_invalid")?;
        let prefix: [u8; 4] = bytes
            .get(..4)
            .ok_or("ssh_host_key_invalid")?
            .try_into()
            .map_err(|_| "ssh_host_key_invalid")?;
        let algorithm_length = u32::from_be_bytes(prefix) as usize;
        if bytes.get(4..4 + algorithm_length) != Some(algorithm.as_bytes())
            || bytes.len() < 4 + algorithm_length + 4
        {
            return Err("ssh_host_key_invalid");
        }
        Ok(Self {
            algorithm: algorithm.to_string(),
            public_key: general_purpose::STANDARD.encode(&bytes),
            fingerprint: format!(
                "SHA256:{}",
                general_purpose::STANDARD_NO_PAD.encode(Sha256::digest(&bytes))
            ),
        })
    }
}

/// Safe durable metadata. `credential_file` is generated by this Runner and is
/// accepted only from the private registry, never a model/operator request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct StoredSshConnection {
    pub(crate) id: String,
    pub(crate) endpoint: SshEndpoint,
    pub(crate) authentication: StoredAuthentication,
    pub(crate) identity_file: Option<String>,
    pub(crate) credential_file: Option<String>,
    pub(crate) host_key: HostKey,
}

#[derive(Debug, Clone)]
pub(crate) struct ManagedSshConnection {
    pub(crate) stored: StoredSshConnection,
    pub(crate) private_root: PathBuf,
    lease: Option<Arc<PrivateFileLease>>,
}

impl PartialEq for ManagedSshConnection {
    fn eq(&self, other: &Self) -> bool {
        self.stored == other.stored && self.private_root == other.private_root
    }
}
impl Eq for ManagedSshConnection {}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct PrivateCredential {
    binding: String,
    secret: SshSecret,
}

impl StoredSshConnection {
    pub(crate) fn validate(&self) -> Result<(), &'static str> {
        self.endpoint.validate()?;
        if !valid_id(&self.id)
            || HostKey::parse(&self.host_key.algorithm, &self.host_key.public_key)
                .map_err(|_| "ssh_resource_invalid")?
                != self.host_key
        {
            return Err("ssh_resource_invalid");
        }
        if self
            .credential_file
            .as_deref()
            .is_some_and(|name| name != format!("credential-{}.json", self.id))
        {
            return Err("ssh_resource_invalid");
        }
        match self.authentication {
            StoredAuthentication::ExistingEnvironment
                if self.identity_file.is_none() && self.credential_file.is_none() =>
            {
                Ok(())
            }
            StoredAuthentication::Password
                if self.identity_file.is_none() && self.credential_file.is_some() =>
            {
                Ok(())
            }
            StoredAuthentication::IdentityFile
                if self
                    .identity_file
                    .as_deref()
                    .is_some_and(valid_identity_path) =>
            {
                Ok(())
            }
            _ => Err("ssh_resource_invalid"),
        }
    }

    fn binding(&self) -> Result<String, &'static str> {
        let encoded = serde_json::to_vec(self).map_err(|_| "ssh_resource_invalid")?;
        Ok(format!("{:x}", Sha256::digest(encoded)))
    }

    pub(crate) fn known_hosts_name(&self) -> String {
        format!("hosts-{}.txt", self.id)
    }

    fn host_alias(&self) -> String {
        format!("webcodex-{}", self.id)
    }

    pub(crate) fn file_names(&self) -> Vec<String> {
        let mut names = vec![self.known_hosts_name()];
        names.extend(self.credential_file.iter().cloned());
        names
    }
}

/// Candidate files are removed on every failed probe/commit. Only a completed
/// durable registry write transfers their lifetime to the managed resource.
pub(crate) struct ConnectionCandidate {
    pub(crate) connection: ManagedSshConnection,
    files: Vec<String>,
    retained: bool,
}

impl ConnectionCandidate {
    pub(crate) fn create(
        root: &Path,
        endpoint: SshEndpoint,
        authentication: SshAuthentication,
        host_key: HostKey,
    ) -> Result<Self, &'static str> {
        let store = PrivateFileStore::open(root).map_err(|_| "ssh_credentials_unavailable")?;
        let id = uuid::Uuid::new_v4().simple().to_string();
        let (kind, identity_file, secret) = match authentication {
            SshAuthentication::ExistingEnvironment => {
                (StoredAuthentication::ExistingEnvironment, None, None)
            }
            SshAuthentication::Password { password } => {
                (StoredAuthentication::Password, None, Some(password))
            }
            SshAuthentication::IdentityFile { path, passphrase } => {
                validate_identity_file(&path)?;
                (StoredAuthentication::IdentityFile, Some(path), passphrase)
            }
        };
        let credential_file = secret.as_ref().map(|_| format!("credential-{id}.json"));
        let stored = StoredSshConnection {
            id,
            endpoint,
            authentication: kind,
            identity_file,
            credential_file,
            host_key,
        };
        stored.validate()?;
        let mut candidate = Self {
            connection: ManagedSshConnection {
                stored,
                private_root: root.to_path_buf(),
                lease: None,
            },
            files: Vec::new(),
            retained: false,
        };
        if let Some(secret) = secret {
            validate_secret(secret.expose_secret())?;
            let credential = PrivateCredential {
                binding: candidate.connection.stored.binding()?,
                secret,
            };
            let bytes =
                serde_json::to_vec(&credential).map_err(|_| "ssh_credentials_unavailable")?;
            let name = candidate
                .connection
                .stored
                .credential_file
                .as_ref()
                .ok_or("ssh_credentials_unavailable")?;
            store
                .create(name, &bytes)
                .map_err(|_| "ssh_credentials_unavailable")?;
            candidate.files.push(name.clone());
        }
        let stored = &candidate.connection.stored;
        let known_hosts = format!(
            "{} {} {}\n",
            stored.host_alias(),
            stored.host_key.algorithm,
            stored.host_key.public_key
        );
        let name = stored.known_hosts_name();
        store
            .create(&name, known_hosts.as_bytes())
            .map_err(|_| "ssh_credentials_unavailable")?;
        candidate.files.push(name);
        candidate.connection.acquire_lease()?;
        Ok(candidate)
    }

    pub(crate) fn retain(&mut self) {
        self.retained = true;
    }
}

impl Drop for ConnectionCandidate {
    fn drop(&mut self) {
        if !self.retained {
            self.connection.lease.take();
            if let Ok(store) = PrivateFileStore::existing(&self.connection.private_root) {
                let hosts = self.connection.stored.known_hosts_name();
                if self.files.contains(&hosts) {
                    if let Ok(Some(lease)) = store.try_exclusive_lease(&hosts) {
                        for name in self.files.iter().filter(|name| **name != hosts) {
                            let _ = store.remove(name);
                        }
                        let _ = store.remove_leased(&lease);
                    }
                } else {
                    for name in &self.files {
                        let _ = store.remove(name);
                    }
                }
            }
        }
    }
}

fn valid_id(value: &str) -> bool {
    value.len() == 32 && value.bytes().all(|byte| byte.is_ascii_hexdigit())
}

fn valid_identity_path(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 4096
        && Path::new(value).is_absolute()
        && !value.chars().any(char::is_control)
}

fn validate_identity_file(value: &str) -> Result<(), &'static str> {
    if !valid_identity_path(value) {
        return Err("ssh_identity_file_invalid");
    }
    let metadata = std::fs::symlink_metadata(value).map_err(|_| "ssh_identity_file_invalid")?;
    if !metadata.is_file() || metadata.is_symlink() {
        return Err("ssh_identity_file_invalid");
    }
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        if metadata.file_attributes() & 0x400 != 0 {
            return Err("ssh_identity_file_invalid");
        }
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        if metadata.uid() != unsafe { libc::geteuid() } || metadata.mode() & 0o077 != 0 {
            return Err("ssh_client_permission_denied");
        }
    }
    Ok(())
}

fn validate_secret(secret: &str) -> Result<(), &'static str> {
    if secret.is_empty() || secret.len() > SECRET_MAX_BYTES || secret.contains(['\0', '\r', '\n']) {
        return Err("ssh_resource_invalid");
    }
    Ok(())
}

fn option_path(path: &Path) -> Result<String, &'static str> {
    let value = path.to_str().ok_or("ssh_credentials_unavailable")?;
    if value.chars().any(char::is_control) {
        return Err("ssh_credentials_unavailable");
    }
    // -o is parsed as ssh_config syntax; quoting is necessary for Windows user
    // directories and other paths containing spaces. This is not shell quoting.
    Ok(format!(
        "\"{}\"",
        value.replace('\\', "\\\\").replace('"', "\\\"")
    ))
}

fn configure_path_arguments(
    command: &mut Command,
    hosts_path: &Path,
    identity_path: Option<&str>,
    windows: bool,
) -> Result<(), &'static str> {
    let global_hosts_path = option_path(hosts_path)?;
    let user_hosts_path = if windows {
        // Win32 OpenSSH expands ${variables} through the narrow CRT getenv,
        // which can lose Unicode paths. Its argv is converted from UTF-16 to
        // UTF-8 instead. Keep paths in argv; the only expansion value is the
        // forced ASCII dollar below, never an inherited value or a full path.
        command
            .env_remove(KNOWN_HOSTS_PATH_ENV)
            .env_remove(IDENTITY_PATH_ENV)
            .env(LITERAL_DOLLAR_ENV, "$");
        windows_expanding_option_path(hosts_path)?
    } else {
        // OpenSSH appends an environment expansion without recursively scanning
        // its value. Preserve the existing Unix literal-path behavior.
        command
            .env(KNOWN_HOSTS_PATH_ENV, hosts_path)
            .env_remove(IDENTITY_PATH_ENV)
            .env_remove(LITERAL_DOLLAR_ENV);
        format!("${{{KNOWN_HOSTS_PATH_ENV}}}")
    };
    command
        .arg("-o")
        .arg(format!("UserKnownHostsFile={user_hosts_path}"))
        .arg("-o")
        .arg(format!("GlobalKnownHostsFile={global_hosts_path}"));
    if let Some(path) = identity_path {
        let identity = if windows {
            windows_expanding_option_path(Path::new(path))?
        } else {
            command.env(IDENTITY_PATH_ENV, path);
            format!("${{{IDENTITY_PATH_ENV}}}")
        };
        // Do not use -i: it stats its argument before the later percent/dollar
        // expansion, so an escaped literal path would name a different file.
        command.arg("-o").arg(format!("IdentityFile={identity}"));
    }
    Ok(())
}

fn windows_expanding_option_path(path: &Path) -> Result<String, &'static str> {
    let value = path.to_str().ok_or("ssh_credentials_unavailable")?;
    let mut encoded = String::new();
    for character in value.chars() {
        match character {
            '%' => encoded.push_str("%%"),
            '$' => {
                encoded.push_str("${");
                encoded.push_str(LITERAL_DOLLAR_ENV);
                encoded.push('}');
            }
            character if character.is_control() => return Err("ssh_credentials_unavailable"),
            character => encoded.push(character),
        }
        // Bound expansion memory separately from the final UTF-16 command-line
        // check. Never truncate or retarget a path that cannot be represented.
        if encoded.len() > WINDOWS_PATH_OPTION_MAX_BYTES {
            return Err("ssh_credentials_unavailable");
        }
    }
    option_path(Path::new(&encoded))
}

#[cfg(any(windows, test))]
fn windows_utf16_units(value: &std::ffi::OsStr) -> Result<usize, &'static str> {
    #[cfg(windows)]
    let units = {
        use std::os::windows::ffi::OsStrExt;
        value.encode_wide()
    };
    #[cfg(not(windows))]
    let units = value
        .to_str()
        .ok_or("ssh_credentials_unavailable")?
        .encode_utf16();
    let mut length = 0usize;
    for unit in units {
        if unit == 0 || length >= WINDOWS_COMMAND_LINE_MAX_UNITS {
            return Err("ssh_credentials_unavailable");
        }
        length += 1;
    }
    Ok(length)
}

/// Check only fully constructed Windows commands, immediately before handing
/// them to their spawn owner. Rust quotes the original program and can at most
/// double each normal argument unit while escaping quotes/backslashes. Include
/// every argument, separator and the terminating NUL; no raw_arg is used here.
#[cfg(any(windows, test))]
pub(crate) fn validate_windows_command(command: &Command) -> Result<(), &'static str> {
    let unavailable = "ssh_credentials_unavailable";
    let mut length = windows_utf16_units(command.get_program())?
        .checked_add(3)
        .ok_or(unavailable)?;
    for argument in command.get_args() {
        let argument_length = windows_utf16_units(argument)?
            .checked_mul(2)
            .and_then(|length| length.checked_add(3))
            .ok_or(unavailable)?;
        length = length.checked_add(argument_length).ok_or(unavailable)?;
        if length > WINDOWS_COMMAND_LINE_MAX_UNITS {
            return Err(unavailable);
        }
    }
    if length > WINDOWS_COMMAND_LINE_MAX_UNITS {
        return Err(unavailable);
    }
    Ok(())
}

fn windows_askpass_leaf(name: &str) -> Result<String, &'static str> {
    if name.len() <= 4
        || !name
            .get(name.len() - 4..)
            .is_some_and(|suffix| suffix.eq_ignore_ascii_case(".exe"))
        || !name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
    {
        return Err("ssh_credentials_unavailable");
    }
    // The explicit relative path cannot search PATH. Do not allow whitespace,
    // quotes or separators: Win32 OpenSSH can parse '.exe ' as exe + arguments.
    Ok(format!(r".\{name}"))
}

fn configure_askpass_program(
    command: &mut Command,
    executable: &Path,
    windows: bool,
) -> Result<(), &'static str> {
    if windows {
        if !executable.is_absolute() {
            return Err("ssh_credentials_unavailable");
        }
        let parent = executable.parent().ok_or("ssh_credentials_unavailable")?;
        let name = executable
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or("ssh_credentials_unavailable")?;
        // SSH_ASKPASS also passes through narrow getenv. The actual image's
        // safe ASCII leaf avoids that conversion; CreateProcessW inherits this
        // wide child-only cwd. Only authentication leases call this helper.
        command
            .env("SSH_ASKPASS", windows_askpass_leaf(name)?)
            .current_dir(parent);
    } else {
        command.env("SSH_ASKPASS", executable);
    }
    Ok(())
}

impl ManagedSshConnection {
    pub(crate) fn load(
        stored: StoredSshConnection,
        private_root: PathBuf,
    ) -> Result<Self, &'static str> {
        let mut connection = Self {
            stored,
            private_root,
            lease: None,
        };
        connection.stored.validate()?;
        connection.acquire_lease()?;
        Ok(connection)
    }

    fn acquire_lease(&mut self) -> Result<(), &'static str> {
        let store = PrivateFileStore::existing(&self.private_root)
            .map_err(|_| "ssh_credentials_unavailable")?;
        let lease = store
            .shared_lease(&self.stored.known_hosts_name())
            .map_err(|_| "ssh_credentials_unavailable")?;
        self.lease = Some(Arc::new(lease));
        Ok(())
    }

    pub(crate) fn configure(
        &self,
        command: &mut Command,
        allow_authentication: bool,
    ) -> Result<Option<AskpassLease>, &'static str> {
        self.stored.validate()?;
        let store = PrivateFileStore::existing(&self.private_root)
            .map_err(|_| "ssh_credentials_unavailable")?;
        let hosts_name = self.stored.known_hosts_name();
        let expected = format!(
            "{} {} {}\n",
            self.stored.host_alias(),
            self.stored.host_key.algorithm,
            self.stored.host_key.public_key
        );
        if store
            .read(&hosts_name, 16 * 1024)
            .map_err(|_| "ssh_credentials_unavailable")?
            != expected.as_bytes()
        {
            return Err("ssh_credentials_unavailable");
        }
        let hosts_path = store
            .path(&hosts_name)
            .map_err(|_| "ssh_credentials_unavailable")?;
        command
            .arg("-F")
            .arg("none")
            .arg("-p")
            .arg(self.stored.endpoint.port.to_string())
            .arg("-l")
            .arg(&self.stored.endpoint.user);
        configure_path_arguments(
            command,
            &hosts_path,
            self.stored.identity_file.as_deref(),
            cfg!(windows),
        )?;
        for option in [
            "StrictHostKeyChecking=yes".to_string(),
            format!("HostKeyAlias={}", self.stored.host_alias()),
            "CheckHostIP=no".to_string(),
            "UpdateHostKeys=no".to_string(),
            "VerifyHostKeyDNS=no".to_string(),
            "PermitLocalCommand=no".to_string(),
            "ClearAllForwardings=yes".to_string(),
            "ForwardAgent=no".to_string(),
            "ForwardX11=no".to_string(),
            "KbdInteractiveAuthentication=no".to_string(),
            "NumberOfPasswordPrompts=1".to_string(),
            "ConnectTimeout=10".to_string(),
            "ServerAliveInterval=5".to_string(),
            "ServerAliveCountMax=2".to_string(),
        ] {
            command.arg("-o").arg(option);
        }
        let host_algorithms = if self.stored.host_key.algorithm == "ssh-rsa" {
            "rsa-sha2-512,rsa-sha2-256"
        } else {
            self.stored.host_key.algorithm.as_str()
        };
        command
            .arg("-o")
            .arg(format!("HostKeyAlgorithms={host_algorithms}"));
        command
            .env("LC_ALL", "C")
            .env_remove("SSH_ASKPASS")
            .env_remove("SSH_ASKPASS_REQUIRE")
            .env_remove("SSH_ASKPASS_PROMPT")
            .env_remove(ASKPASS_REQUEST_ENV)
            .env_remove(ASKPASS_NONCE_ENV)
            .env_remove(DIAGNOSTICS_ENV)
            .env_remove("SSHPASS");
        match self.stored.authentication {
            StoredAuthentication::ExistingEnvironment => {
                command.arg("-o").arg("PasswordAuthentication=no");
            }
            StoredAuthentication::Password => {
                command
                    .arg("-o")
                    .arg("PreferredAuthentications=password")
                    .arg("-o")
                    .arg("PubkeyAuthentication=no")
                    .arg("-o")
                    .arg("PasswordAuthentication=yes");
            }
            StoredAuthentication::IdentityFile => {
                command
                    .arg("-o")
                    .arg("IdentitiesOnly=yes")
                    .arg("-o")
                    .arg("PreferredAuthentications=publickey")
                    .arg("-o")
                    .arg("PasswordAuthentication=no");
            }
        }
        let lease = if allow_authentication && self.stored.credential_file.is_some() {
            Some(AskpassLease::prepare(self, command)?)
        } else {
            None
        };
        command.arg("-o").arg(if lease.is_some() {
            "BatchMode=no"
        } else {
            "BatchMode=yes"
        });
        Ok(lease)
    }
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct AskpassRequest {
    nonce: String,
    expires_at: u64,
    binding: String,
    credential_file: String,
    authentication: StoredAuthentication,
    endpoint: SshEndpoint,
    host_alias: String,
    identity_file: Option<String>,
}

/// Holds only private file names; dropping it removes the one-use request even
/// when spawning, authentication, cancellation, or command preparation fails.
#[derive(Debug)]
pub(crate) struct AskpassLease {
    store: PrivateFileStore,
    name: String,
    used_name: String,
    _profile_lease: Arc<PrivateFileLease>,
}

impl AskpassLease {
    fn prepare(
        connection: &ManagedSshConnection,
        command: &mut Command,
    ) -> Result<Self, &'static str> {
        let store = PrivateFileStore::existing(&connection.private_root)
            .map_err(|_| "ssh_credentials_unavailable")?;
        let nonce = uuid::Uuid::new_v4().simple().to_string();
        let name = format!("askpass-{nonce}.json");
        let used_name = format!("used-{nonce}.json");
        let request = AskpassRequest {
            nonce: nonce.clone(),
            expires_at: now_seconds()?.saturating_add(ASKPASS_LIFETIME_SECS),
            binding: connection.stored.binding()?,
            credential_file: connection
                .stored
                .credential_file
                .clone()
                .ok_or("ssh_credentials_unavailable")?,
            authentication: connection.stored.authentication.clone(),
            endpoint: connection.stored.endpoint.clone(),
            host_alias: connection.stored.host_alias(),
            identity_file: connection.stored.identity_file.clone(),
        };
        let bytes = serde_json::to_vec(&request).map_err(|_| "ssh_credentials_unavailable")?;
        let path = store
            .create(&name, &bytes)
            .map_err(|_| "ssh_credentials_unavailable")?;
        let lease = Self {
            store,
            name,
            used_name,
            _profile_lease: connection
                .lease
                .clone()
                .ok_or("ssh_credentials_unavailable")?,
        };
        let executable = std::env::current_exe().map_err(|_| "ssh_credentials_unavailable")?;
        configure_askpass_program(command, &executable, cfg!(windows))?;
        command
            .env("SSH_ASKPASS_REQUIRE", "force")
            .env(ASKPASS_REQUEST_ENV, path)
            .env(ASKPASS_NONCE_ENV, nonce);
        Ok(lease)
    }
}

impl Drop for AskpassLease {
    fn drop(&mut self) {
        let _ = self.store.remove(&self.name);
        let _ = self.store.remove(&self.used_name);
    }
}

fn now_seconds() -> Result<u64, &'static str> {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_secs())
        .map_err(|_| "ssh_credentials_unavailable")
}

/// Called before CLI parsing, tracing, service handling, or any other output.
pub(crate) fn maybe_run_askpass() -> Option<i32> {
    let path = std::env::var_os(ASKPASS_REQUEST_ENV)?;
    let diagnostics = std::env::var(DIAGNOSTICS_ENV).as_deref() == Ok("1");
    record_stage(
        diagnostics,
        AskpassStage::Entered,
        &mut std::io::stderr().lock(),
    );
    let result = (|| {
        // OpenSSH truncates key names to 100 bytes in its passphrase prompt,
        // which can split UTF-8. Keep the original Unix bytes before normal
        // Runner CLI parsing; std::env::args() would panic on that prompt.
        let args: Vec<_> = std::env::args_os().skip(1).collect();
        if args.len() != 1
            || std::env::var("SSH_ASKPASS_PROMPT").is_ok_and(|value| !value.is_empty())
        {
            return Err(AskpassStage::Arguments);
        }
        #[cfg(unix)]
        let prompt = {
            use std::os::unix::ffi::OsStrExt;
            args[0].as_bytes().to_vec()
        };
        #[cfg(not(unix))]
        let prompt = args[0].to_string_lossy().as_bytes().to_vec();
        if prompt.len() > 8192 {
            return Err(AskpassStage::Arguments);
        }
        let nonce = std::env::var(ASKPASS_NONCE_ENV).map_err(|_| AskpassStage::Nonce)?;
        let secret = askpass_secret(Path::new(&path), &nonce, &prompt)?;
        let mut stdout = std::io::stdout().lock();
        stdout
            .write_all(secret.expose_secret().as_bytes())
            .and_then(|()| stdout.write_all(b"\n"))
            .and_then(|()| stdout.flush())
            .map_err(|_| AskpassStage::Stdout)
    })();
    record_stage(
        diagnostics,
        result
            .as_ref()
            .map_or_else(|stage| *stage, |_| AskpassStage::Complete),
        &mut std::io::stderr().lock(),
    );
    Some(if result.is_ok() { 0 } else { 1 })
}

fn askpass_secret(
    path: &Path,
    nonce: &str,
    prompt: impl AsRef<[u8]>,
) -> Result<SshSecret, AskpassStage> {
    let prompt = prompt.as_ref();
    if !valid_id(nonce) {
        return Err(AskpassStage::Nonce);
    }
    if prompt.iter().any(u8::is_ascii_control) {
        return Err(AskpassStage::Prompt);
    }
    let root = path.parent().ok_or(AskpassStage::RequestPath)?;
    let name = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or(AskpassStage::RequestPath)?;
    if name != format!("askpass-{nonce}.json") {
        return Err(AskpassStage::RequestPath);
    }
    let store = PrivateFileStore::existing(root).map_err(|_| AskpassStage::RequestStore)?;
    let bytes = store
        .read(name, SECRET_FILE_MAX_BYTES)
        .map_err(|_| AskpassStage::RequestRead)?;
    let request: AskpassRequest =
        serde_json::from_slice(&bytes).map_err(|_| AskpassStage::RequestDecode)?;
    let now = now_seconds().map_err(|_| AskpassStage::Clock)?;
    if request.nonce != nonce {
        return Err(AskpassStage::Nonce);
    }
    if request.expires_at < now || request.expires_at > now.saturating_add(ASKPASS_LIFETIME_SECS) {
        return Err(AskpassStage::Expiry);
    }
    if !prompt_matches(&request, prompt) {
        return Err(AskpassStage::Prompt);
    }
    // Exclusive creation is the linearization point: retries and concurrent
    // askpass processes cannot release this request's secret a second time.
    store
        .create(&format!("used-{nonce}.json"), b"used")
        .map_err(|_| AskpassStage::Consume)?;
    let bytes = store
        .read(&request.credential_file, SECRET_FILE_MAX_BYTES)
        .map_err(|_| AskpassStage::CredentialRead)?;
    let credential: PrivateCredential =
        serde_json::from_slice(&bytes).map_err(|_| AskpassStage::CredentialDecode)?;
    if credential.binding != request.binding {
        return Err(AskpassStage::Binding);
    }
    validate_secret(credential.secret.expose_secret()).map_err(|_| AskpassStage::Secret)?;
    Ok(credential.secret)
}

fn prompt_matches(request: &AskpassRequest, prompt: impl AsRef<[u8]>) -> bool {
    let prompt = prompt.as_ref();
    // OpenSSH uses HostKeyAlias in its password prompt when one is set. The
    // alias is generated by this exact pinned connection, never supplied by
    // an operator/model or accepted as an arbitrary hostname wildcard.
    if !request
        .host_alias
        .strip_prefix("webcodex-")
        .is_some_and(|id| {
            valid_id(id) && request.credential_file == format!("credential-{id}.json")
        })
    {
        return false;
    }
    match request.authentication {
        StoredAuthentication::Password => std::str::from_utf8(prompt)
            .ok()
            .and_then(|prompt| prompt.strip_suffix("'s password: "))
            .and_then(|destination| destination.rsplit_once('@'))
            .is_some_and(|(user, host)| {
                user == request.endpoint.user
                    && (host == request.host_alias
                        || match (
                            host.parse::<std::net::IpAddr>(),
                            request.endpoint.host.parse::<std::net::IpAddr>(),
                        ) {
                            (Ok(actual), Ok(expected)) => actual == expected,
                            (Err(_), Err(_)) => host
                                .trim_end_matches('.')
                                .eq_ignore_ascii_case(request.endpoint.host.trim_end_matches('.')),
                            _ => false,
                        })
            }),
        StoredAuthentication::IdentityFile => request
            .identity_file
            .as_ref()
            .is_some_and(|path| key_prompt_matches(path, prompt, cfg!(windows))),
        StoredAuthentication::ExistingEnvironment => false,
    }
}

fn key_prompt_matches(path: &str, prompt: &[u8], windows_argv: bool) -> bool {
    let normalized_prompt = prompt
        .iter()
        .map(|byte| if *byte == b'\\' { b'/' } else { *byte })
        .collect::<Vec<_>>();
    let normalized_path = path.replace('\\', "/");
    let path_bytes = normalized_path.as_bytes();
    [path_bytes.len(), path_bytes.len().min(100)]
        .into_iter()
        .any(|length| {
            let mut expected = b"Enter passphrase for key '".to_vec();
            expected.extend_from_slice(&path_bytes[..length]);
            expected.extend_from_slice(b"': ");
            // Win32 OpenSSH converts this UTF-8 command line with
            // MultiByteToWideChar(CP_UTF8, 0) before CreateProcessW. If %.100s
            // split a key-path character, that exact suffix becomes U+FFFD.
            // Project only the bound key's expected prompt; received prompts
            // remain exact, and Unix keeps its original argv bytes.
            let expected = if windows_argv {
                String::from_utf8_lossy(&expected).into_owned().into_bytes()
            } else {
                expected
            };
            normalized_prompt == expected
        })
}

pub(crate) fn collect_expired_askpass(store: &PrivateFileStore) {
    let (Ok(names), Ok(now)) = (store.file_names(512), now_seconds()) else {
        return;
    };
    for name in names {
        if let Some(nonce) = name
            .strip_prefix("used-")
            .and_then(|name| name.strip_suffix(".json"))
        {
            if valid_id(nonce) {
                if let Ok(request) = store.path(&format!("askpass-{nonce}.json")) {
                    if std::fs::symlink_metadata(request)
                        .is_err_and(|error| error.kind() == std::io::ErrorKind::NotFound)
                    {
                        let _ = store.remove(&name);
                    }
                }
            }
            continue;
        }
        let Some(nonce) = name
            .strip_prefix("askpass-")
            .and_then(|name| name.strip_suffix(".json"))
        else {
            continue;
        };
        if !valid_id(nonce) {
            continue;
        }
        let Ok(bytes) = store.read(&name, SECRET_FILE_MAX_BYTES) else {
            continue;
        };
        let Ok(request) = serde_json::from_slice::<AskpassRequest>(&bytes) else {
            continue;
        };
        if request.nonce == nonce && request.expires_at < now {
            let _ = store.remove(&name);
            let _ = store.remove(&format!("used-{nonce}.json"));
        }
    }
}

